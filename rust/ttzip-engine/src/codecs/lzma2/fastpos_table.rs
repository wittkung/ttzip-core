//! FastPos 4096 Slot Lookup Table and Logarithmic Distance Converter for LZMA/LZMA2.
//!
//! Maps match distances to 6-bit LZMA position slots (0..63) in constant time.
//! Provides a 64-byte cacheline-aligned 4096-entry static lookup table for short distances (0..4095)
//! mapping directly to slots 0..23, and constant-time logarithmic slot computation for large distances
//! using `leading_zeros` combined with fast table lookups.

use std::ops::{Deref, Index};

/// Number of fast distance bits (12 bits = 4096 entries).
pub const K_FAST_DIST_BITS: usize = 12;

/// Total size of the FastPos lookup table (4096 entries).
pub const FAST_POS_TABLE_SIZE: usize = 1 << K_FAST_DIST_BITS;

/// 64-byte cacheline-aligned container for the 4096-entry FastPos lookup table.
#[repr(C, align(64))]
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct FastPosTable(pub [u8; FAST_POS_TABLE_SIZE]);

impl Deref for FastPosTable {
    type Target = [u8; FAST_POS_TABLE_SIZE];

    #[inline(always)]
    fn deref(&self) -> &Self::Target {
        &self.0
    }
}

impl AsRef<[u8]> for FastPosTable {
    #[inline(always)]
    fn as_ref(&self) -> &[u8] {
        &self.0
    }
}

impl Index<usize> for FastPosTable {
    type Output = u8;

    #[inline(always)]
    fn index(&self, index: usize) -> &Self::Output {
        &self.0[index]
    }
}

