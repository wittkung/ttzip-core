/// Computes the 6-bit LZMA/LZMA2 position slot (0..63) for any 32-bit match distance in constant time.
///
/// For short distances (`dist < 4096`), it directly looks up the precomputed 64-byte aligned table.
/// For larger distances (`dist >= 4096`), it computes the slot using CPU leading zero count (`lzcnt`/`clz`)
/// combined with the lookup table for constant-time $O(1)$ evaluation without variable branching.
#[inline(always)]
pub fn get_pos_slot(dist: u32) -> u32 {
    if dist < FAST_POS_TABLE_SIZE as u32 {
        get_pos_slot_fast(dist)
    } else {
        let lz = dist.leading_zeros();
        let shift = 20 - lz;
        let idx = (dist >> shift) as usize;
        (FAST_POS_TABLE[idx] as u32) + (shift << 1)
    }
}

/// Branchless inline position slot lookup for short distances (`dist < 4096`).
///
/// # Safety / Precondition
/// `dist` must be strictly less than `FAST_POS_TABLE_SIZE` (4096).
#[inline(always)]
pub fn get_pos_slot_fast(dist: u32) -> u32 {
    debug_assert!(
        (dist as usize) < FAST_POS_TABLE_SIZE,
        "dist {} exceeds FAST_POS_TABLE_SIZE (4096)",
        dist
    );
    FAST_POS_TABLE[dist as usize] as u32
}

/// Canonical mathematical specification of LZMA position slot calculation.
///
/// Formulated as $2 \times \lfloor\log_2(D)\rfloor + \text{offset}$ for $D \ge 4$, and $D$ for $D < 4$.
#[inline]
pub fn get_pos_slot_math_spec(dist: u32) -> u32 {
    if dist < 4 {
        dist
    } else {
        let log2 = 31 - dist.leading_zeros();
        let offset = (dist >> (log2 - 1)) & 1;
        (log2 << 1) + offset
    }
}
