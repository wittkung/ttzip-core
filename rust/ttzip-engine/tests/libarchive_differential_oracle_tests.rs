/// Checks if a system CLI binary exists and is executable.
fn is_tool_available(path: &str) -> bool {
    let p = Path::new(path);
    p.exists() && p.is_file()
}

/// Helper RAII test sandbox for isolated bidirectional differential tests.
struct TestSandbox {
    _temp_dir: TempDir,
    root: PathBuf,
    source_dir: PathBuf,
    system_out_dir: PathBuf,
    ttzip_out_dir: PathBuf,
}

impl TestSandbox {
    fn new(prefix: &str) -> Self {
        let temp_dir = tempfile::Builder::new()
            .prefix(prefix)
            .tempdir()
            .expect("failed to create temporary test sandbox");
        let root = temp_dir.path().to_path_buf();
        let source_dir = root.join("src_tree");
        let system_out_dir = root.join("sys_extracted");
        let ttzip_out_dir = root.join("ttzip_extracted");

        fs::create_dir_all(&source_dir).expect("failed to create src_tree dir");
        fs::create_dir_all(&system_out_dir).expect("failed to create sys_extracted dir");
        fs::create_dir_all(&ttzip_out_dir).expect("failed to create ttzip_extracted dir");

        Self {
            _temp_dir: temp_dir,
            root,
            source_dir,
            system_out_dir,
            ttzip_out_dir,
        }
    }

    /// Recursively collects immediate child paths of the source directory.
    fn source_children(&self) -> Vec<PathBuf> {
        let mut paths = Vec::new();
        if let Ok(entries) = fs::read_dir(&self.source_dir) {
            for entry in entries.flatten() {
                paths.push(entry.path());
            }
        }
        paths.sort();
        paths
    }
}

// MARK: - Rich Multi-Layer Tree Generator

/// Populates `source_dir` with a multi-layered, heterogeneous file tree.
fn populate_complex_test_tree(sandbox: &TestSandbox) {
    let src = &sandbox.source_dir;

    // 1. Regular text file at root
    let root_txt = src.join("readme.txt");
    fs::write(&root_txt, b"TTZip System Differential Oracle Ground Truth Data\n").unwrap();
    fs::set_permissions(&root_txt, fs::Permissions::from_mode(0o644)).unwrap();

    // 2. Empty file
    let empty_file = src.join("empty.zero");
    File::create(&empty_file).unwrap();
    fs::set_permissions(&empty_file, fs::Permissions::from_mode(0o644)).unwrap();

    // 3. Executable script
    let bin_dir = src.join("bin");
    fs::create_dir_all(&bin_dir).unwrap();
    let script = bin_dir.join("run.sh");
    fs::write(&script, b"#!/bin/sh\necho \"Executing differential check\"\n").unwrap();
    fs::set_permissions(&script, fs::Permissions::from_mode(0o755)).unwrap();

    // 4. Read-only configuration file
    let conf_dir = src.join("config");
    fs::create_dir_all(&conf_dir).unwrap();
    let ro_conf = conf_dir.join("system.conf");
    fs::write(&ro_conf, b"[oracle]\nmode=strict_differential\nlevel=maximum\n").unwrap();
    fs::set_permissions(&ro_conf, fs::Permissions::from_mode(0o444)).unwrap();

    // 5. Deeply nested hierarchy (Depth 5)
    let deep_dir = src.join("deep").join("l1").join("l2").join("l3").join("l4");
    fs::create_dir_all(&deep_dir).unwrap();
    let deep_file = deep_dir.join("leaf_payload.dat");
    let mut large_pattern = Vec::with_capacity(32 * 1024);
    for i in 0..(32 * 1024) {
        large_pattern.push((i % 251) as u8);
    }
    fs::write(&deep_file, &large_pattern).unwrap();
    fs::set_permissions(&deep_file, fs::Permissions::from_mode(0o644)).unwrap();

    // 6. Empty directory
    let empty_dir = src.join("empty_folder");
    fs::create_dir_all(&empty_dir).unwrap();

    // 7. Unicode & Emoji filenames (NFC normalized UTF-8)
    let u_dir = src.join("unicode");
    fs::create_dir_all(&u_dir).unwrap();
    let u_file1 = u_dir.join("日本語_テスト_仕様書.txt");
    fs::write(&u_file1, "日本語UTF-8差分テストデータ：高精度検証".as_bytes()).unwrap();
    let u_file2 = u_dir.join("中文_苹果架构_🚀.md");
    fs::write(&u_file2, "# 苹果芯片原生微内核差分测试\n性能卓越！".as_bytes()).unwrap();

    // 8. Symbolic links
    let links_dir = src.join("links");
    fs::create_dir_all(&links_dir).unwrap();
    let link_to_readme = links_dir.join("symlink_to_readme.txt");
    symlink("../readme.txt", &link_to_readme).unwrap();

    let link_to_deep = links_dir.join("symlink_to_deep.dat");
    symlink("../deep/l1/l2/l3/l4/leaf_payload.dat", &link_to_deep).unwrap();

    // 9. Hardlinks (linking to root readme)
    let hardlink_file = src.join("hardlink_readme.txt");
    fs::hard_link(&root_txt, &hardlink_file).unwrap();
}

// MARK: - 5-Dimension Oracle Verification Helper

/// Validates that `actual_dir` exactly matches `expected_dir` across all 5 dimensions.
fn assert_differential_oracle_match(
    expected_dir: &Path,
    actual_dir: &Path,
    is_tar_format: bool,
    oracle_name: &str,
    format_name: &str,
) {
    let expected_manifest = scan_directory_tree(expected_dir)
        .unwrap_or_else(|e| panic!("failed scanning expected manifest at {:?}: {:?}", expected_dir, e));
    let actual_manifest = scan_directory_tree(actual_dir)
        .unwrap_or_else(|e| panic!("failed scanning actual manifest at {:?}: {:?}", actual_dir, e));

    let report = compare_manifests(
        &actual_manifest,
        &expected_manifest,
        is_tar_format,
        oracle_name,
        format_name,
    );

    if !report.is_passed {
        eprintln!("=======================================================");
        eprintln!("DIFFERENTIAL ORACLE DIVERGENCE DETECTED [{} / {}]", oracle_name, format_name);
        for (i, err) in report.divergence_errors.iter().enumerate() {
            eprintln!("  [{:02}] {}", i + 1, err);
        }
        if let Some(diff) = &report.hex_diff_output {
            eprintln!("--- Binary Hex Diff ---\n{}", diff);
        }
        eprintln!("=======================================================");
        panic!(
            "Differential Oracle failed with {} divergence errors between {:?} and {:?}",
            report.divergence_errors.len(),
            expected_dir,
            actual_dir
        );
    }

    assert!(report.is_passed);
    assert_eq!(report.divergence_errors.len(), 0);
}

// MARK: - Direction 1: System CLI -> TTZip Extraction Tests

#[test]
fn test_direction1_bsdtar_to_ttzip_differential() {
    if !is_tool_available(SYSTEM_TAR_PATH) {
        eprintln!("[SKIP] System bsdtar not found at {}, skipping test.", SYSTEM_TAR_PATH);
        return;
    }

    let sandbox = TestSandbox::new("ttzip_diff_d1_tar");
    populate_complex_test_tree(&sandbox);

    let tar_archive = sandbox.root.join("system_created.tar");

    // 1. Pack with system bsdtar (/usr/bin/tar -cf <tar_archive> .)
    let tar_status = Command::new(SYSTEM_TAR_PATH)
        .arg("-cf")
        .arg(&tar_archive)
        .arg(".")
        .current_dir(&sandbox.source_dir)
        .status()
        .expect("failed executing system bsdtar -cf");
    assert!(tar_status.success(), "system bsdtar creation failed");

    // 2. Extract with TTZip UnifiedArchiveOrchestrator
    let extract_opts = TTZipExtractOptions {
        preserve_permissions: true,
        overwrite_existing: true,
        ..Default::default()
    };
    UnifiedArchiveOrchestrator::extract_archive(&tar_archive, &sandbox.ttzip_out_dir, &extract_opts)
        .expect("TTZip extraction of system tar archive failed");

    // 3. 5-Dimension Oracle Differential Comparison
    assert_differential_oracle_match(
        &sandbox.source_dir,
        &sandbox.ttzip_out_dir,
        true,
        "bsdtar",
        "tar",
    );
}

