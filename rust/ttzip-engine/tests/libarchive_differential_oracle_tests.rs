// MARK: - Bidirectional Symlink & Hardlink End-to-End Stress Test

#[test]
fn test_bidirectional_symlink_hardlink_permission_fidelity() {
    if !is_tool_available(SYSTEM_TAR_PATH) {
        eprintln!("[SKIP] System bsdtar not found, skipping bidirectional stress test.");
        return;
    }

    let sandbox = TestSandbox::new("ttzip_diff_bidi_stress");
    let src = &sandbox.source_dir;

    // 1. Setup multi-link and permission-sensitive file layout
    let data_file = src.join("data_target.bin");
    fs::write(&data_file, vec![0x5A; 16384]).unwrap();
    fs::set_permissions(&data_file, fs::Permissions::from_mode(0o644)).unwrap();

    let exec_file = src.join("runner.sh");
    fs::write(&exec_file, b"#!/bin/sh\nexit 0\n").unwrap();
    fs::set_permissions(&exec_file, fs::Permissions::from_mode(0o755)).unwrap();

    let ro_file = src.join("readonly.meta");
    fs::write(&ro_file, b"IMMUTABLE_METADATA_BLOCK").unwrap();
    fs::set_permissions(&ro_file, fs::Permissions::from_mode(0o444)).unwrap();

    let sub = src.join("sub");
    fs::create_dir_all(&sub).unwrap();
    let sub_symlink = sub.join("rel_symlink.bin");
    symlink("../data_target.bin", &sub_symlink).unwrap();

    let hardlink_entry = sub.join("hardlink_to_data.bin");
    fs::hard_link(&data_file, &hardlink_entry).unwrap();

    // 2. TTZip -> System Tar -> TTZip Roundtrip
    let tar_p1 = sandbox.root.join("stage1_ttzip.tar");
    let sources = sandbox.source_children();

    let create_opts = TTZipCreateOptions {
        format: TTZipArchiveFormat::Tar,
        level: TTZipCompressionLevel::Normal,
        ..Default::default()
    };
    UnifiedArchiveOrchestrator::create_archive(&sources, &tar_p1, &create_opts, 0)
        .expect("Stage 1 TTZip create_archive failed");

    // System unpacks Stage 1
    let s1_status = Command::new(SYSTEM_TAR_PATH)
        .arg("-xf")
        .arg(&tar_p1)
        .arg("-C")
        .arg(&sandbox.system_out_dir)
        .status()
        .expect("failed executing system bsdtar -xf on Stage 1");
    assert!(s1_status.success());

    // 3. System repacks Stage 1 output
    let tar_p2 = sandbox.root.join("stage2_system.tar");
    let s2_status = Command::new(SYSTEM_TAR_PATH)
        .arg("-cf")
        .arg(&tar_p2)
        .arg(".")
        .current_dir(&sandbox.system_out_dir)
        .status()
        .expect("failed executing system bsdtar -cf on Stage 2");
    assert!(s2_status.success());

    // 4. TTZip unpacks Stage 2 output
    let extract_opts = TTZipExtractOptions {
        preserve_permissions: true,
        overwrite_existing: true,
        ..Default::default()
    };
    UnifiedArchiveOrchestrator::extract_archive(&tar_p2, &sandbox.ttzip_out_dir, &extract_opts)
        .expect("Stage 2 TTZip extract_archive failed");

    // 5. Oracle verification against initial source tree
    assert_differential_oracle_match(
        &sandbox.source_dir,
        &sandbox.ttzip_out_dir,
        true,
        "roundtrip_bsdtar",
        "tar",
    );
}
