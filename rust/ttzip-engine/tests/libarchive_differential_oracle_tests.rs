//! Comprehensive Bidirectional Differential Test Suite & 5-Dimension Oracle (Task 16.10).
//!
//! Validates zero-divergence and bit-exact interoperability against macOS / POSIX native CLI tools:
//! - System `bsdtar` (`/usr/bin/tar` - libarchive)
//! - System `bsdcpio` (`/usr/bin/cpio` - libarchive)
//! - System `unzip` / `zip` (`/usr/bin/unzip`, `/usr/bin/zip` - Info-ZIP / Apple)
//!
//! Test Dimensions:
//! 1. **Direction 1 (System -> TTZip)**:
//!    Archives created by system tools (`bsdtar`, `bsdcpio`, `zip`) are extracted by TTZip's
//!    `UnifiedArchiveOrchestrator` and `SecurePathExtractor`, verifying 100% extraction fidelity.
//! 2. **Direction 2 (TTZip -> System)**:
//!    Archives generated by TTZip (TAR, CPIO, ZIP) are extracted by native system CLI tools,
//!    asserting 0 warnings, 0 errors, and byte-exact roundtrip restoration.
//! 3. **5-Dimension Differential Oracle**:
//!    Strict assertions across Relative Path, Size, SHA-256 Checksum, POSIX Mode/Permissions,
//!    and Symlink Target.
//! 4. **Edge Cases**:
//!    Deep nested directories, empty files, empty directories, Unicode filenames (UTF-8/NFC),
//!    hardlinks, symlinks, and distinct permission masks (`0o755`, `0o644`, `0o444`).

