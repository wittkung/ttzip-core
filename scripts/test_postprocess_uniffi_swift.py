class TestPostprocessUniFFISwift(unittest.TestCase):
    """Test suite covering invariant enforcement and Swift syntax validation."""

    def test_cli_help(self):
        """CLI --help flag prints usage and exits cleanly with 0."""
        self.assertTrue(bool(POSTPROCESS_SCRIPT), "postprocess_uniffi_swift.py not found in candidate paths")
        result = subprocess.run(
            [sys.executable, POSTPROCESS_SCRIPT, "--help"],
            stdout=subprocess.PIPE,
            stderr=subprocess.PIPE,
            text=True,
        )
        self.assertEqual(result.returncode, 0)
        self.assertIn("--verify-only", result.stdout)
        self.assertIn("swift_file", result.stdout)

    def test_verify_only_on_repo_file(self):
        """--verify-only succeeds on the repository's generated ttzip_engine.swift."""
        self.assertTrue(bool(REPO_FILE), "ttzip_engine.swift not found in candidate paths")
        result = subprocess.run(
            [sys.executable, POSTPROCESS_SCRIPT, "--verify-only", REPO_FILE],
            stdout=subprocess.PIPE,
            stderr=subprocess.PIPE,
            text=True,
        )
        self.assertEqual(result.returncode, 0, f"Stderr: {result.stderr}")
        self.assertIn("satisfies all UniFFI Swift 6 concurrency", result.stdout)

    def test_postprocess_raw_uniffi_pipeline(self):
        """Raw UniFFI code undergoes all patches, satisfies assertions, and validates syntax."""
        patched, changed = postprocess_content(MOCK_RAW_UNIFFI_SWIFT, verify_only=False)
        self.assertTrue(changed)

        # Invariants assertion
        self.assertTrue(patched.startswith("// Copyright 2026 MetastudyLine"))
        self.assertIn("#if canImport(TTZipEngineFFI)", patched)
        self.assertIn("nonisolated(unsafe) static var vtable:", patched)
        self.assertIn("nonisolated(unsafe) fileprivate static var handleMap =", patched)
        self.assertIn("private let initializationResult:", patched)
        self.assertNotIn('print("Uniffi callback interface', patched)
        self.assertIn("extension UniFfiVfsTree: @unchecked Sendable {}", patched)
        self.assertIn("defer { buf.deallocate() }", patched)
        self.assertIn("_ = try? rustCall { uniffi_ttzip_engine_fn_free_cancellationtoken", patched)
        self.assertIn("callStatus.errorBuf.deallocate()", patched)
        self.assertIn("throw CancellationError()", patched)
        self.assertIn("guard let data = rustBuffer.data, rustBuffer.len > 0 else", patched)
        self.assertIn("guard self.data != nil && self.capacity > 0 else { return }", patched)

        # Verify Swift syntax validation passes on result
        validate_swift_syntax(patched)

        # Re-running verification on patched output must pass
        is_compliant, violations = verify_invariants(patched)
        self.assertTrue(is_compliant, f"Violations detected: {violations}")

    def test_fail_fast_on_missing_required_pattern(self):
        """If a required patch cannot match and its invariant is missing, aborts with RuntimeError."""
        # Corrupt the raw lift function signature
        broken_raw = MOCK_RAW_UNIFFI_SWIFT.replace(
            "public static func lift(_ buf: RustBuffer)",
            "public static func liftUnexpectedRenamedSignature(_ buf: RustBuffer)",
        )
        with self.assertRaises(RuntimeError) as ctx:
            postprocess_content(broken_raw, verify_only=False)
        self.assertIn("defer_rustbuffer_deallocate_in_lift", str(ctx.exception))
        self.assertIn("failed assertion", str(ctx.exception))

    def test_syntax_validator_detects_imbalance(self):
        """Syntax validator fails on unbalanced braces, brackets, or unclosed comments."""
        # Unclosed brace
        bad_braces = "func test() { if true { print(1) }"
        with self.assertRaises(SyntaxError) as ctx:
            validate_swift_syntax(bad_braces)
        self.assertIn("Unclosed delimiter '{'", str(ctx.exception))

        # Mismatched bracket
        mismatched = "let arr = [1, 2, 3)"
        with self.assertRaises(SyntaxError) as ctx:
            validate_swift_syntax(mismatched)
        self.assertIn("Mismatched delimiter", str(ctx.exception))

        # Unclosed multi-line comment
        unclosed_comment = "/* starting comment func foo() {}"
        with self.assertRaises(SyntaxError) as ctx:
            validate_swift_syntax(unclosed_comment)
        self.assertIn("Unterminated multi-line comment", str(ctx.exception))

    def test_verify_only_cli_on_unprocessed_file(self):
        """--verify-only on an unprocessed file fails with exit code 1 without writing changes."""
        with tempfile.NamedTemporaryFile("w+", suffix=".swift", delete=False) as tf:
            tf.write(MOCK_RAW_UNIFFI_SWIFT)
            tf_path = tf.name

        try:
            self.assertTrue(bool(POSTPROCESS_SCRIPT), "postprocess_uniffi_swift.py not found in candidate paths")
            result = subprocess.run(
                [sys.executable, POSTPROCESS_SCRIPT, "--verify-only", tf_path],
                stdout=subprocess.PIPE,
                stderr=subprocess.PIPE,
                text=True,
            )
            self.assertEqual(result.returncode, 1)
            self.assertIn("[GATE FAILURE]", result.stderr)

            # Ensure file on disk was NOT modified
            with open(tf_path, "r") as f:
                disk_content = f.read()
            self.assertEqual(disk_content, MOCK_RAW_UNIFFI_SWIFT)
        finally:
            if os.path.exists(tf_path):
                os.remove(tf_path)


if __name__ == "__main__":
    unittest.main()
